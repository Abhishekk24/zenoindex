// Regenerates src/abis.ts from zenoindex-evm at the exact commit deployed to mainnet.
// Builds from `git archive <commit>` in a temp dir, so the evm repo's working tree is never touched.
//
// Usage: node scripts/gen-abis.mjs [--evm <path-to-zenoindex-evm>]
// Env:   FORGE=<path to forge binary> (default: forge on PATH, then ~/.foundry/bin/forge)

import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { homedir, tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// Keep in sync with EVM_COMMIT in src/constants.ts.
const EVM_COMMIT = "bf57915";
const CONTRACTS = [
  ["ZenoIndexVault", "ZenoIndexVault.sol"],
  ["Vault", "Vault.sol"],
  ["ShareToken", "ShareToken.sol"],
  ["AccessMaster", "AccessMaster.sol"],
  ["UniswapV4Adapter", "UniswapV4Adapter.sol"],
  ["FeeEscrow", "FeeEscrow.sol"],
];

const here = dirname(fileURLToPath(import.meta.url));
const argIdx = process.argv.indexOf("--evm");
const evmRepo = resolve(argIdx > 0 ? process.argv[argIdx + 1] : join(here, "../../../../zenoindex-evm"));
const outFile = join(here, "../src/abis.ts");

function forgeBin() {
  if (process.env.FORGE) return process.env.FORGE;
  try {
    execFileSync("forge", ["--version"], { stdio: "ignore" });
    return "forge";
  } catch {
    const exe = join(homedir(), ".foundry", "bin", process.platform === "win32" ? "forge.exe" : "forge");
    if (existsSync(exe)) return exe;
    throw new Error("forge not found: install Foundry or set FORGE");
  }
}

if (!existsSync(join(evmRepo, ".git"))) throw new Error(`not a git repo: ${evmRepo} (pass --evm <path>)`);
// Fails loudly if the deployed commit isn't available locally (git fetch in the evm repo).
execFileSync("git", ["-C", evmRepo, "cat-file", "-e", `${EVM_COMMIT}^{commit}`], { stdio: "inherit" });

const tmp = mkdtempSync(join(tmpdir(), "zenoindex-abis-"));
try {
  const tarball = execFileSync("git", ["-C", evmRepo, "archive", "--format=tar", EVM_COMMIT, "src", "lib", "foundry.toml"], {
    maxBuffer: 512 * 1024 * 1024,
  });
  execFileSync("tar", ["-x", "-f", "-", "-C", tmp], { input: tarball });
  console.log(`building zenoindex-evm@${EVM_COMMIT} in ${tmp}`);
  execFileSync(forgeBin(), ["build", "--root", tmp, "--skip", "test", "--skip", "script"], { stdio: "inherit" });

  let ts = `// Generated by scripts/gen-abis.mjs from zenoindex-evm@${EVM_COMMIT}. Do not edit by hand.\n`;
  for (const [name, file] of CONTRACTS) {
    const artifact = JSON.parse(readFileSync(join(tmp, "out", file, `${name}.json`), "utf8"));
    ts += `\nexport const ${name}Abi = ${JSON.stringify(artifact.abi)} as const;\n`;
  }
  writeFileSync(outFile, ts);
  console.log(`wrote ${outFile}`);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
